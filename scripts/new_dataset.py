"""Inspect an .h5ad and scaffold a config + ground-truth template for a new two-condition dataset.

    python scripts/new_dataset.py data/my.h5ad --name mydata
    # writes config/mydata.yaml and data/ground_truth/mydata.yaml (template), prints what it found

It guesses the sample / condition / cell-type columns, the counts location and the species from
the gene symbols; every guess is printed and written as a comment so you can correct it.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def guess_species(var_names) -> str:
    v = [str(x) for x in var_names[:5000]]
    if any(x.startswith("ENSCAFG") for x in v):
        return "canis_lupus_familiaris"
    if any(x.startswith("ENSMUSG") for x in v):
        return "mus_musculus"
    if any(x.startswith("ENSG") for x in v):
        return "homo_sapiens"
    symbols = [x for x in v if re.match(r"^[A-Za-z][A-Za-z0-9-]+$", x)]
    if not symbols:
        return "homo_sapiens"
    title = sum(1 for x in symbols if x[0].isupper() and x[1:].islower() and len(x) > 2)
    upper = sum(1 for x in symbols if x.isupper())
    return "mus_musculus" if title > upper else "homo_sapiens"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("h5ad")
    ap.add_argument("--name", required=True)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args(argv)
    import anndata as ad
    import numpy as np
    import scipy.sparse as sp

    adata = ad.read_h5ad(a.h5ad, backed="r")
    obs = adata.obs
    print(f"{adata.n_obs} cells x {adata.n_vars} genes")
    cat_cols = [c for c in obs.columns if obs[c].dtype.name in ("category", "object", "bool") and 1 < obs[c].nunique() <= 200]
    print("\ncategorical obs columns (n unique): " + ", ".join(f"{c} ({obs[c].nunique()})" for c in cat_cols))
    low = {c: c.lower() for c in cat_cols}
    sample_key = next((c for c in cat_cols if low[c] in ("sample", "sample_id", "library", "orig.ident", "donor", "patient", "batch")), None)
    cond_key = next((c for c in cat_cols if low[c] in ("condition", "disease", "group", "status", "treatment", "diagnosis", "tumor_status", "disease_state")), None)
    ct_key = next((c for c in cat_cols if any(k in low[c] for k in ("cell_type", "celltype", "annotation", "lineage", "broad"))), None)
    if cond_key is None:
        two = [c for c in cat_cols if 2 <= obs[c].nunique() <= 3 and c != sample_key]
        cond_key = two[0] if two else None
    conds = list(obs[cond_key].astype(str).unique()) if cond_key else []
    n_per = obs.groupby(cond_key)[sample_key].nunique().to_dict() if (cond_key and sample_key) else {}
    X = adata[:200].to_memory().X
    Xd = X.toarray() if sp.issparse(X) else np.asarray(X)
    counts_layer = None
    looks_counts = bool(np.allclose(Xd, np.round(Xd)) and Xd.max() > 20)
    for layer in adata.layers.keys():
        L = adata[:200].to_memory().layers[layer]
        Ld = L.toarray() if sp.issparse(L) else np.asarray(L)
        if np.allclose(Ld, np.round(Ld)) and Ld.max() > 20:
            counts_layer = layer
            break
    species = guess_species(list(adata.var_names))
    clusterings = [c for c in obs.columns if re.search(r"leiden|louvain|cluster|seurat_clusters", c, re.I)]
    print(f"\nguesses: sample_key={sample_key}  condition_key={cond_key} {conds}  celltype_key={ct_key}  species={species}")
    print(f"         X looks like counts: {looks_counts}; counts layer: {counts_layer}; existing clusterings: {clusterings}; embeddings: {list(adata.obsm.keys())}")
    print(f"         samples per condition: {n_per}")
    warn = []
    if not sample_key:
        warn.append("no sample column found: per-sample tests need one")
    if cond_key and len(conds) != 2:
        warn.append(f"{len(conds)} condition levels: set disease (case) to one and reference to the rest")
    if n_per and min(n_per.values()) < 3:
        warn.append("fewer than 3 samples in a condition: pseudobulk and per-sample abundance will be weak")
    if not looks_counts and not counts_layer:
        warn.append("no raw counts found: pseudobulk DE needs them")
    for w in warn:
        print("WARNING:", w)

    cfg_path = Path("config") / f"{a.name}.yaml"
    gt_path = Path("data/ground_truth") / f"{a.name}.yaml"
    if (cfg_path.exists() or gt_path.exists()) and not a.force:
        print(f"\n{cfg_path} or {gt_path} exists; use --force to overwrite"); return
    disease = conds[0] if conds else "DISEASE"
    reference = conds[1:] if len(conds) > 1 else ["CONTROL"]
    cfg_path.write_text(f"""# generated by scripts/new_dataset.py - every value below is a guess to check
dataset:
  path: {a.h5ad}
  species: {species}
  sample_key: {sample_key or 'SAMPLE_COLUMN'}
  condition_key: {cond_key or 'CONDITION_COLUMN'}
  celltype_key: {ct_key or 'null'}            # null -> lineages are derived from the data
  disease: {disease}                            # the 'case' condition (treated / disease / knockout)
  reference: {reference}
  condition_descriptions:
    {disease}: "DESCRIBE"
  counts_layer: {counts_layer or 'null'}            # null = counts are in X; the loader copies them to layer 'counts' before normalising
  already_processed: {'true' if clusterings or adata.obsm.keys() else 'false'}
  reuse_clustering: {clusterings[0] if clusterings else 'null'}
  forbidden_obs_columns: []                     # anything identifying (names, dates, IDs)
  exclude_samples: []                           # libraries to drop, with exclude_samples_reason; a disclosed choice recorded in every run
  exclude_samples_reason: null
targets:
  objective: target                             # or marker for a perturbation / response study
agent:
  max_turns_per_role: 60
""")
    gt_path.parent.mkdir(parents=True, exist_ok=True)
    gt_path.write_text(f"""# Frozen answer key for {a.name}. Fill from the literature BEFORE the first model run; commit; never edit after.
expected_states:
  - name: STATE_NAME
    marker_genes: []            # 6-20 genes from the published analysis
    min_marker_overlap: 4
expected_targets: []            # the published, independently validated target(s)
acceptable_targets: []          # right biology, not a drug target (markers of the state)
expected_drugs: []              # compounds you would accept (generic names)
decoy_targets: []               # druggable but obviously wrong: proliferation genes, lineage markers, pan-condition genes
per_cell_truth: null
""")
    print(f"\nwrote {cfg_path} and {gt_path} (template). Next: edit both, `git add` + commit the key, then\n  SCTARGET_OFFLINE=1 python scripts/run_pipeline.py --config {cfg_path} --model scripted --run-dir runs/{a.name}_dry1")


if __name__ == "__main__":
    main()
