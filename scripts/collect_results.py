"""Regenerate the results table from the run directories themselves.

    python scripts/collect_results.py --ground-truth data/ground_truth/caa.yaml runs/caa_* --out docs/results_caa.md
    python scripts/collect_results.py --ground-truth data/ground_truth/ccrcc.yaml runs/ccrcc_* --out docs/results_ccrcc.md

Each row is one run; the arm label is read from the run's own config_used.json and state.json
(model, prompt_version, scoring_version, ignore_annotation, reuse_clustering, resume), so every
number in a write-up traces to a run directory, not to memory. Also writes <out>.json.
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sctarget.eval import evaluate_run  # noqa: E402


def arm_label(run_dir: Path) -> str:
    cfg = json.loads((run_dir / "config_used.json").read_text()) if (run_dir / "config_used.json").exists() else {}
    st = json.loads((run_dir / "state.json").read_text()) if (run_dir / "state.json").exists() else {}
    facts = st.get("facts", {})
    parts = []
    model = None
    try:
        with open(run_dir / "run.jsonl") as fh:
            for line in fh:
                e = json.loads(line)
                if e.get("type") == "model_call":
                    model = e.get("model")
                    break
    except FileNotFoundError:
        pass
    parts.append(model or "scripted/baseline")
    parts.append(f"prompts v{facts.get('prompt_version', cfg.get('prompt_version', 1))}")
    parts.append(f"scoring v{facts.get('scoring_version', cfg.get('targets', {}).get('scoring_version', 1))}")
    ds = cfg.get("dataset", {})
    if ds.get("reuse_clustering"):
        parts.append("reused clustering")
    else:
        parts.append("de novo clustering")
    if cfg.get("analysis", {}).get("lineages", {}).get("ignore_annotation") or not ds.get("celltype_key"):
        parts.append("derived lineages")
    if (run_dir / "rescore.json").exists():
        parts.append("rescored")
    return "; ".join(parts)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ground-truth", required=True)
    ap.add_argument("--out", required=True, help="markdown table path (a .json sibling is written too)")
    ap.add_argument("run_dirs", nargs="+")
    a = ap.parse_args(argv)
    rows = []
    for d in sorted(a.run_dirs):
        p = Path(d)
        if not p.is_dir() or not (p / "state.json").exists():
            continue
        try:
            r = evaluate_run(p, a.ground_truth)
        except Exception as e:  # a run that stopped before producing state: record it as such
            rows.append({"run": p.name, "arm": arm_label(p), "error": f"{type(e).__name__}: {str(e)[:80]}"})
            continue
        sr = next(iter(r.state_recovery.values()), {})
        bm = sr.get("best_match") or {}
        sb = sr.get("best_match_strict") or {}
        tr = r.target_rank
        rows.append({
            "run": p.name,
            "arm": arm_label(p),
            "state_found": bool(sr.get("found")),
            "state_overlap": f"{bm.get('overlap')}/{sr.get('required_overlap')}",
            "strict_found": bool(sr.get("found_strict")),
            "strict_overlap": f"{sb.get('overlap')}/{sr.get('required_overlap')}",
            "target_rank": ", ".join(f"{g}:{v if v is not None else '-'}" for g, v in tr.items()),
            "acceptable_rank": ", ".join(f"{g}:{v if v is not None else '-'}" for g, v in (r.acceptable_rank or {}).items()),
            "decoys_above": len(r.decoys_above_target),
            "novel_above": len(r.novel_above_target),
            "decoys_unflagged": len(r.decoys_nominated_unflagged),
            "n_nominated": len(r.nominated),
            "precision": round(r.nominated_precision, 2) if r.nominated_precision is not None else None,
            "drug_recall": r.drug_recall,
            "tool_calls": r.n_tool_calls,
            "tool_errors": r.n_tool_errors,
            "input_tokens": (r.tokens or {}).get("input_tokens"),
            "pass": r.passed,
        })
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    cols = ["run", "arm", "state_found", "state_overlap", "strict_found", "strict_overlap", "target_rank", "acceptable_rank", "decoys_above", "novel_above", "decoys_unflagged", "n_nominated", "precision", "drug_recall", "tool_calls", "tool_errors", "input_tokens", "pass"]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in rows:
        lines.append("| " + " | ".join(str(row.get(c, row.get("error", ""))) if c != "arm" else str(row.get("arm", "")) for c in cols) + " |")
    out.write_text(f"# Results: {Path(a.ground_truth).stem}\n\nGenerated by scripts/collect_results.py from the run directories; arm labels come from each run's own config_used.json.\n\n" + "\n".join(lines) + "\n")
    out.with_suffix(".json").write_text(json.dumps(rows, indent=2, default=str))
    print("\n".join(lines))
    print(f"\nwrote {out} and {out.with_suffix('.json')}")


if __name__ == "__main__":
    main()
